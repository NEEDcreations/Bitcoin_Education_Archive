function scamHostAllowed(host) {
    let h = String(host || '').toLowerCase().replace(/\.+$/, '').replace(/^www\./, '');
    while (h.indexOf('.') !== -1) {
        if (SCAM_ALLOW_HOSTS.has(h)) return true;
        h = h.slice(h.indexOf('.') + 1);
    }
    return false;
}

